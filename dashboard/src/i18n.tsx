export const TRANSLATIONS = Object.fromEntries(rows.map(([fr, en, ar, darija]) => [fr, { fr, en, ar, darija }])) as Record<string, Record<Language, string>>;
let language: Language = 'fr';
try { const saved = localStorage.getItem('sahhanito.staff.language'); if (LANGUAGES.some(([code]) => code === saved)) language = saved as Language; } catch { /* private browser */ }
const listeners = new Set<() => void>();
export const getLanguage = () => language;
export const locale = () => language === 'en' ? 'en-GB' : language === 'fr' ? 'fr-TN' : 'ar-TN';
function setDocumentLanguage() { document.documentElement.lang = language === 'darija' ? 'ar-TN' : language; document.documentElement.dir = language === 'ar' || language === 'darija' ? 'rtl' : 'ltr'; }
setDocumentLanguage();
export function t(source: string, values: Record<string, string | number> = {}, target = language) {
  const text = TRANSLATIONS[source]?.[target] ?? source;
  return text.replace(/\{(\w+)\}/g, (all, key) => String(values[key] ?? all));
}
export function useLanguage() {
  return useSyncExternalStore(callback => { listeners.add(callback); return () => { listeners.delete(callback); }; }, getLanguage);
}
export function setLanguage(next: Language) {
  language = next; setDocumentLanguage();
  try { localStorage.setItem('sahhanito.staff.language', next); } catch { /* private browser */ }
  listeners.forEach(callback => callback());
}
export function LanguageSelect() {
  const current = useLanguage();
  return <label className="flex items-center gap-2 text-xs">{t('Langue')}
    <select className="min-h-10 rounded-lg border bg-card px-2 text-sm" aria-label={t('Langue')} value={current} onChange={e => setLanguage(e.target.value as Language)}>
      {LANGUAGES.map(([code, label]) => <option key={code} value={code}>{label}</option>)}
    </select>
  </label>;
}
